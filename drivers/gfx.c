static void vga_write_reg(uint16_t port, uint8_t reg, uint8_t val) {
    outb(port, reg);
    outb(port + 1, val);
}

/* Program VGA Mode 13h (320x200x256) without BIOS */
void gfx_init_mode13(void) {
    /* misc output */
    outb(0x3C2, 0x63);

    /* sequencer */
    vga_write_reg(0x3C4, 0x00, 0x03);
    vga_write_reg(0x3C4, 0x01, 0x01);
    vga_write_reg(0x3C4, 0x02, 0x0F);
    vga_write_reg(0x3C4, 0x03, 0x00);
    vga_write_reg(0x3C4, 0x04, 0x0E);

    /* unlock CRTC */
    outb(0x3D4, 0x11);
    outb(0x3D5, inb(0x3D5) & 0x7F);

    /* CRTC */
    static const uint8_t crtc[25] = {
        0x5F, 0x4F, 0x50, 0x82, 0x54, 0x80, 0xBF, 0x1F,
        0x00, 0x41, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x9C, 0x0E, 0x8F, 0x28, 0x40, 0x96, 0xB9, 0xA3,
        0xFF};
    for (uint8_t i = 0; i < 25; i++)
        vga_write_reg(0x3D4, i, crtc[i]);

    /* graphics controller */
    static const uint8_t gc[9] = {
        0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x05, 0x0F, 0xFF};
    for (uint8_t i = 0; i < 9; i++)
        vga_write_reg(0x3CE, i, gc[i]);

    /* attribute controller */
    for (uint8_t i = 0; i < 16; i++) {
        (void)inb(0x3DA);
        outb(0x3C0, i);
        outb(0x3C0, i);
    }
    (void)inb(0x3DA);
    outb(0x3C0, 0x10);
    outb(0x3C0, 0x41);
    (void)inb(0x3DA);
    outb(0x3C0, 0x11);
    outb(0x3C0, 0x00);
    (void)inb(0x3DA);
    outb(0x3C0, 0x12);
    outb(0x3C0, 0x0F);
    (void)inb(0x3DA);
    outb(0x3C0, 0x13);
    outb(0x3C0, 0x00);
    (void)inb(0x3DA);
    outb(0x3C0, 0x14);
    outb(0x3C0, 0x00);
    (void)inb(0x3DA);
    outb(0x3C0, 0x20); /* unblank */

    /* simple 16-color palette into DAC */
    static const uint8_t pal[16][3] = {
        {0, 0, 0},    {0, 0, 42},   {0, 42, 0},   {0, 42, 42},
        {42, 0, 0},   {42, 0, 42},  {42, 21, 0},  {42, 42, 42},
        {21, 21, 21}, {21, 21, 63}, {21, 63, 21}, {21, 63, 63},
        {63, 21, 21}, {63, 21, 63}, {63, 63, 21}, {63, 63, 63},
    };
    outb(0x3C8, 0);
    for (int i = 0; i < 16; i++) {
        outb(0x3C9, pal[i][0]);
        outb(0x3C9, pal[i][1]);
        outb(0x3C9, pal[i][2]);
    }

    graphics_on = 1;
    gfx_clear(GFX_BLACK);
}

/* Approximate restore to 80x25 text mode 3 */
void gfx_restore_text(void) {
    outb(0x3C2, 0x67);
    vga_write_reg(0x3C4, 0x00, 0x03);
    vga_write_reg(0x3C4, 0x01, 0x00);
    vga_write_reg(0x3C4, 0x02, 0x03);
    vga_write_reg(0x3C4, 0x03, 0x00);
    vga_write_reg(0x3C4, 0x04, 0x02);

    outb(0x3D4, 0x11);
    outb(0x3D5, inb(0x3D5) & 0x7F);

    static const uint8_t crtc[25] = {
        0x5F, 0x4F, 0x50, 0x82, 0x55, 0x81, 0xBF, 0x1F,
        0x00, 0x4F, 0x0D, 0x0E, 0x00, 0x00, 0x00, 0x00,
        0x9C, 0x8E, 0x8F, 0x28, 0x1F, 0x96, 0xB9, 0xA3,
        0xFF};
    for (uint8_t i = 0; i < 25; i++)
        vga_write_reg(0x3D4, i, crtc[i]);

    static const uint8_t gc[9] = {
        0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x0E, 0x00, 0xFF};
    for (uint8_t i = 0; i < 9; i++)
        vga_write_reg(0x3CE, i, gc[i]);

    for (uint8_t i = 0; i < 16; i++) {
        (void)inb(0x3DA);
        outb(0x3C0, i);
        outb(0x3C0, i);
    }
    (void)inb(0x3DA);
    outb(0x3C0, 0x10);
    outb(0x3C0, 0x0C);
    (void)inb(0x3DA);
    outb(0x3C0, 0x11);
    outb(0x3C0, 0x00);
    (void)inb(0x3DA);
    outb(0x3C0, 0x12);
    outb(0x3C0, 0x0F);
    (void)inb(0x3DA);
    outb(0x3C0, 0x13);
    outb(0x3C0, 0x08);
    (void)inb(0x3DA);
    outb(0x3C0, 0x14);
    outb(0x3C0, 0x00);
    (void)inb(0x3DA);
    outb(0x3C0, 0x20);

    graphics_on = 0;
}

int gfx_is_graphics(void) { return graphics_on; }

void gfx_clear(uint8_t color) {
    memset(GFX_FB, color, GFX_WIDTH * GFX_HEIGHT);
}

void gfx_putpixel(int x, int y, uint8_t color) {
    if ((unsigned)x >= GFX_WIDTH || (unsigned)y >= GFX_HEIGHT)
        return;
    GFX_FB[y * GFX_WIDTH + x] = color;
}

uint8_t gfx_getpixel(int x, int y) {
    if ((unsigned)x >= GFX_WIDTH || (unsigned)y >= GFX_HEIGHT)
        return 0;
    return GFX_FB[y * GFX_WIDTH + x];
}

void gfx_fillrect(int x, int y, int w, int h, uint8_t color) {
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            gfx_putpixel(x + i, y + j, color);
}

void gfx_rect(int x, int y, int w, int h, uint8_t color) {
    gfx_hline(x, y, w, color);
    gfx_hline(x, y + h - 1, w, color);
    gfx_vline(x, y, h, color);
    gfx_vline(x + w - 1, y, h, color);
}

void gfx_hline(int x, int y, int w, uint8_t color) {
    for (int i = 0; i < w; i++)
        gfx_putpixel(x + i, y, color);
}

void gfx_vline(int x, int y, int h, uint8_t color) {
    for (int j = 0; j < h; j++)
        gfx_putpixel(x, y + j, color);
}

void gfx_char(int x, int y, char c, uint8_t fg, uint8_t bg) {
    unsigned char uc = (unsigned char)c;
    if (uc < 32 || uc > 127)
        uc = '?';
    const uint8_t *glyph = font8x8[uc - 32];
    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            uint8_t on = bits & (0x80 >> col);
            gfx_putpixel(x + col, y + row, on ? fg : bg);
        }
    }
}

void gfx_text(int x, int y, const char *s, uint8_t fg, uint8_t bg) {
    int cx = x;
    while (s && *s) {
        if (*s == '\n') {
            y += 9;
            cx = x;
            s++;
            continue;
        }
        gfx_char(cx, y, *s, fg, bg);
        cx += 8;
        s++;
    }
}
