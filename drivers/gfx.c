/*
 * OSDev-style VGA register writer.
 * regs layout: MISC(1) + SEQ(5) + CRTC(25) + GC(9) + AC(21)
 */
static void vga_write_regs(const uint8_t *regs) {
    unsigned i;

    /* misc */
    outb(0x3C2, *regs++);

    /* sequencer */
    for (i = 0; i < 5; i++) {
        outb(0x3C4, (uint8_t)i);
        outb(0x3C5, *regs++);
    }

    /* unlock CRTC */
    outb(0x3D4, 0x03);
    outb(0x3D5, inb(0x3D5) | 0x80);
    outb(0x3D4, 0x11);
    outb(0x3D5, inb(0x3D5) & ~0x80);
    /* keep unlock bits in the table values we write */
    {
        uint8_t *cr = (uint8_t *)regs;
        (void)cr;
    }

    /* CRTC */
    for (i = 0; i < 25; i++) {
        outb(0x3D4, (uint8_t)i);
        outb(0x3D5, *regs++);
    }

    /* GC */
    for (i = 0; i < 9; i++) {
        outb(0x3CE, (uint8_t)i);
        outb(0x3CF, *regs++);
    }

    /* AC — reset flip-flop, then index+data pairs */
    for (i = 0; i < 21; i++) {
        (void)inb(0x3DA);
        outb(0x3C0, (uint8_t)i);
        outb(0x3C0, *regs++);
    }

    /* lock 16-color palette and unblank display */
    (void)inb(0x3DA);
    outb(0x3C0, 0x20);
}

