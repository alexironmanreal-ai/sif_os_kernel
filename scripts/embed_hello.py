#!/usr/bin/env python3
"""Embed all userspace ELFs into include/user_elfs.h for the ramfs."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
bin_dir = root / "userspace" / "bin"
out = root / "include" / "user_elfs.h"

elves = [
    ("hello.elf", bin_dir / "hello.elf"),
    ("echo.elf", bin_dir / "echo.elf"),
    ("cat.elf", bin_dir / "cat.elf"),
    ("ls.elf", bin_dir / "ls.elf"),
]

parts = []
table_entries = []

for name, path in elves:
    if not path.is_file():
        print(f"warning: missing {path}, skipping")
        continue
    blob = path.read_bytes()
    sym = name.replace(".", "_").replace("-", "_")
    lines = []
    for i in range(0, len(blob), 12):
        chunk = blob[i : i + 12]
        lines.append(",".join(f"0x{b:02x}" for b in chunk))
    body = ",\n  ".join(lines)
    parts.append(
        f"static const uint8_t {sym}_data[] = {{\n  {body}\n}};\n"
        f"static const uint32_t {sym}_len = {len(blob)};\n"
    )
    table_entries.append(
        f'  {{ "{name}", {sym}_data, {sym}_len }},'
    )
    print(f"embedded {name}: {len(blob)} bytes")

table_entries.append("  { 0, 0, 0 },")

header = f"""/* auto-generated by scripts/embed_hello.py — do not edit */
#ifndef USER_ELFS_H
#define USER_ELFS_H
#include <stdint.h>

{chr(10).join(parts)}
struct user_elf_entry {{
    const char *name;
    const uint8_t *data;
    uint32_t len;
}};

static const struct user_elf_entry user_elf_table[] = {{
{chr(10).join(table_entries)}
}};

#endif
"""

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(header)
print(f"wrote {out}")
